/* sound.js - The Secrets of the Journey
   -------------------------------------------------------------------
   Session sounds + the sound settings panel (bell button).

   What it does
   - Rings a sound when a study session STARTS and another when it ENDS.
   - Settings panel (opens from the bell button #soundBell): on/off,
     volume, and which sound plays at the start / at the end.
   - Settings are saved per device in localStorage (key: sj_sound_v1).

   Sounds
   - 3 files from the folder  sounds/  (bicycle_bell.mp3, soft_bell.mp3,
     supermarket.mp3)
   - 4 extra sounds generated by code (no files needed).

   Public API (window.SJSound)
     watch(phase, sessionId)  -> called by script.js every second.
                                 phase: 'wait' | 'study' | 'break' | 'ended' | 'none'
     play(id)                 -> preview any sound
     open() / close()         -> settings panel
     refreshLang()            -> call after the site language changes
   ------------------------------------------------------------------- */
(function () {
  "use strict";
  if (typeof document === "undefined") return;

  var STORE_KEY = "sj_sound_v1";
  var DEFAULTS = { on: true, vol: 80, start: "soft_bell", end: "bicycle_bell" };
  var STALE_MS = 90 * 1000; // if the page was asleep longer than this, don't ring for an old event

  /* trim = small loudness correction so all sounds feel similar in volume */
  var SOUNDS = [
    { id: "bicycle_bell", file: "sounds/bicycle_bell.mp3", trim: 0.75 },
    { id: "soft_bell", file: "sounds/soft_bell.mp3", trim: 1.1 },
    { id: "supermarket", file: "sounds/supermarket.mp3", trim: 1.1 },
    { id: "ring" },
    { id: "dingdong" },
    { id: "chime" },
    { id: "crystal" },
  ];

  /* ---------- texts (3 languages) ---------- */
  var STR = {
    ar: {
      title: "إعدادات الصوت",
      enable: "تفعيل الأصوات",
      enableHint: "رنّة عند بداية السشن ونهايته",
      volume: "مستوى الصوت",
      start: "صوت بداية السشن",
      end: "صوت نهاية السشن",
      tip: "المس أي صوت لتجربته واختياره",
      saved: "تُحفظ الإعدادات على هذا الجهاز",
      close: "إغلاق",
      locked: "المس الشاشة مرة لتفعيل الصوت",
      names: {
        bicycle_bell: "جرس الدراجة", soft_bell: "جرس ناعم", supermarket: "السوبرماركت",
        ring: "رنّة حادة", dingdong: "دينغ دونغ", chime: "رنين", crystal: "كريستال",
      },
    },
    en: {
      title: "Sound settings",
      enable: "Enable sounds",
      enableHint: "A sound when a session starts and ends",
      volume: "Volume",
      start: "Session start sound",
      end: "Session end sound",
      tip: "Tap a sound to preview and select it",
      saved: "Settings are saved on this device",
      close: "Close",
      locked: "Tap the screen once to allow sound",
      names: {
        bicycle_bell: "Bicycle bell", soft_bell: "Soft bell", supermarket: "Supermarket",
        ring: "Bright ring", dingdong: "Ding-dong", chime: "Chime", crystal: "Crystal",
      },
    },
    ckb: {
      title: "ڕێکخستنی دەنگ",
      enable: "چالاککردنی دەنگەکان",
      enableHint: "دەنگێک کاتی دەستپێکردن و کۆتایی سیشن",
      volume: "ئاستی دەنگ",
      start: "دەنگی دەستپێکردنی سیشن",
      end: "دەنگی کۆتایی سیشن",
      tip: "دەست لە دەنگێک بدە بۆ تاقیکردنەوە و هەڵبژاردنی",
      saved: "ڕێکخستنەکان لەسەر ئەم ئامێرە پاشەکەوت دەکرێن",
      close: "داخستن",
      locked: "یەک جار دەست لە شاشە بدە بۆ چالاککردنی دەنگ",
      names: {
        bicycle_bell: "زەنگی پاسکیل", soft_bell: "زەنگی نەرم", supermarket: "سوپەرمارکێت",
        ring: "زرنگەی تیژ", dingdong: "دینگ دۆنگ", chime: "زرنگە", crystal: "کریستاڵ",
      },
    },
  };

  function lang() {
    var l = "ar";
    try { l = localStorage.getItem("lang") || "ar"; } catch (e) {}
    return STR[l] ? l : "ar";
  }
  function tr(key) { return STR[lang()][key] || STR.en[key] || key; }
  function soundName(id) { return STR[lang()].names[id] || STR.en.names[id] || id; }

  /* ---------- settings (saved on this device) ---------- */
  function findSound(id) {
    for (var i = 0; i < SOUNDS.length; i++) if (SOUNDS[i].id === id) return SOUNDS[i];
    return null;
  }
  function loadSettings() {
    var s = {};
    try { s = JSON.parse(localStorage.getItem(STORE_KEY) || "{}") || {}; } catch (e) { s = {}; }
    var v = Number(s.vol);
    return {
      on: s.on !== false,
      vol: isFinite(v) && s.vol !== null && s.vol !== "" ? Math.max(0, Math.min(100, Math.round(v))) : DEFAULTS.vol,
      start: findSound(s.start) ? s.start : DEFAULTS.start,
      end: findSound(s.end) ? s.end : DEFAULTS.end,
    };
  }
  var settings = loadSettings();
  function saveSettings() {
    try { localStorage.setItem(STORE_KEY, JSON.stringify(settings)); } catch (e) {}
  }

  /* ---------- audio engine (Web Audio: volume works on iPhone/iPad too) ---------- */
  var ctx = null, master = null, current = null;
  var buffers = {}, loading = {};
  function noop() {}

  function volumeGain() { var v = settings.vol / 100; return v * v; } // gentle curve: finer control at low volume
  function applyVolume() { if (master) master.gain.value = volumeGain(); }

  function getCtx() {
    if (ctx) return ctx;
    var AC = window.AudioContext || window.webkitAudioContext;
    if (!AC) return null;
    try {
      // iOS: play even when the silent switch is on
      if (navigator.audioSession) navigator.audioSession.type = "playback";
    } catch (e) {}
    try { ctx = new AC(); } catch (e) { ctx = null; return null; }
    master = ctx.createGain();
    var comp = ctx.createDynamicsCompressor();
    master.connect(comp);
    comp.connect(ctx.destination);
    applyVolume();
    ctx.onstatechange = updateBell;
    return ctx;
  }

  function ensureRunning(c) {
    if (c.state === "running") return Promise.resolve(true);
    var p;
    try { p = c.resume(); } catch (e) { return Promise.resolve(false); }
    return Promise.race([
      Promise.resolve(p).then(function () { return c.state === "running"; }),
      new Promise(function (res) { setTimeout(function () { res(false); }, 800); }),
    ]).catch(function () { return false; });
  }

  function loadBuffer(snd, c) {
    if (buffers[snd.id]) return Promise.resolve(buffers[snd.id]);
    if (loading[snd.id]) return loading[snd.id];
    loading[snd.id] = fetch(snd.file)
      .then(function (r) {
        if (!r.ok) throw new Error("HTTP " + r.status);
        return r.arrayBuffer();
      })
      .then(function (ab) {
        return new Promise(function (res, rej) {
          var p = c.decodeAudioData(ab, res, rej);
          if (p && p.catch) p.catch(rej);
        });
      })
      .then(function (buf) { buffers[snd.id] = buf; return buf; })
      .catch(function (e) {
        delete loading[snd.id];
        console.warn("sound.js: could not load " + snd.file + " (is it inside the sounds folder?)", e);
        throw e;
      });
    return loading[snd.id];
  }
  function preloadSelected() {
    var c = ctx;
    if (!c) return;
    [settings.start, settings.end].forEach(function (id) {
      var s = findSound(id);
      if (s && s.file) loadBuffer(s, c).catch(noop);
    });
  }

  /* ---------- generated sounds ---------- */
  /* partial = [frequencyRatio, amplitude, decayScale] */
  function bellTone(c, bus, freq, t, dur, vol, partials) {
    partials.forEach(function (p) {
      var f = freq * p[0];
      if (f > 16000) return;
      var o = c.createOscillator(), g = c.createGain(), d = dur * p[2];
      o.type = "sine";
      o.frequency.value = f;
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(vol * p[1], t + 0.006);
      g.gain.exponentialRampToValueAtTime(0.0001, t + d);
      o.connect(g); g.connect(bus);
      o.start(t); o.stop(t + d + 0.05);
    });
  }
  var SYNTH = {
    /* bright double "ting-ting" (close to the bicycle bell) */
    ring: function (c, bus, t) {
      var P = [[2, 1, 1], [3.05, 0.55, 0.7], [3.64, 0.3, 0.5], [1, 0.25, 0.4]];
      bellTone(c, bus, 2950, t, 1.9, 0.3, P);
      bellTone(c, bus, 2950, t + 0.17, 1.9, 0.24, P);
    },
    /* two-tone door chime (close to the supermarket sound) */
    dingdong: function (c, bus, t) {
      var P = [[1, 1, 1], [2, 0.4, 0.6], [2.76, 0.25, 0.4], [4.1, 0.1, 0.25]];
      bellTone(c, bus, 659.25, t, 1.4, 0.38, P);
      bellTone(c, bus, 523.25, t + 0.55, 1.8, 0.38, P);
    },
    /* three soft rising notes (close to the soft bell) */
    chime: function (c, bus, t) {
      var P = [[1, 1, 1], [2.76, 0.3, 0.35], [5.4, 0.1, 0.2]];
      bellTone(c, bus, 1318.5, t, 1.3, 0.32, P);
      bellTone(c, bus, 1568, t + 0.15, 1.3, 0.32, P);
      bellTone(c, bus, 1975.5, t + 0.3, 1.8, 0.32, P);
    },
    /* one long glassy note */
    crystal: function (c, bus, t) {
      var P = [[1, 1, 1], [1.004, 0.6, 1], [2.01, 0.35, 0.7], [3.02, 0.2, 0.5], [5.97, 0.1, 0.3]];
      bellTone(c, bus, 1760, t, 2.4, 0.28, P);
    },
  };

  function stopCurrent() {
    var b = current;
    if (!b || !ctx) return;
    try { b.gain.cancelScheduledValues(ctx.currentTime); b.gain.setTargetAtTime(0, ctx.currentTime, 0.015); } catch (e) {}
    setTimeout(function () { try { b.disconnect(); } catch (e) {} }, 400);
    current = null;
  }

  /* play any sound by id. exclusive = cut the previous preview first */
  function play(id, exclusive) {
    var snd = findSound(id);
    var c = getCtx();
    if (!snd || !c) return Promise.resolve(false);
    return ensureRunning(c).then(function (ok) {
      if (!ok) return false;
      var bus = c.createGain();
      bus.connect(master);
      if (exclusive) stopCurrent();
      current = bus;
      ringBell();
      if (snd.file) {
        return loadBuffer(snd, c).then(function (buf) {
          var src = c.createBufferSource();
          src.buffer = buf;
          bus.gain.value = snd.trim || 1;
          src.connect(bus);
          src.start();
          return true;
        }).catch(function () { return false; });
      }
      bus.gain.value = 1;
      SYNTH[snd.id](c, bus, c.currentTime + 0.02);
      return true;
    });
  }

  /* ---------- session start / end detection ---------- */
  var lastPhase = null, lastSid = null, lastAt = 0;
  var events = []; // kept for testing: what rang and when

  function watch(phase, sid) {
    var now = Date.now();
    var stale = lastAt > 0 && now - lastAt > STALE_MS;
    var prev = lastPhase;
    var prevSid = lastSid;
    lastAt = now;
    lastPhase = phase;
    lastSid = sid || null;
    if (prev === null) return; // first look at the page: never ring

    var isStart = phase === "study" && (prev !== "study" || (sid || null) !== prevSid);
    var isEnd = prev === "study" && (phase === "break" || phase === "ended");
    if (stale || !settings.on) return;
    if (isStart) { events.push({ kind: "start", id: settings.start }); play(settings.start, false); }
    else if (isEnd) { events.push({ kind: "end", id: settings.end }); play(settings.end, false); }
  }

  /* ---------- unlock audio on the first touch (browser rule) ---------- */
  function onGesture() {
    if (!ctx) {
      if (getCtx()) {
        try { // a silent blip fully unlocks iOS
          var b = ctx.createBuffer(1, 1, 22050), s = ctx.createBufferSource();
          s.buffer = b; s.connect(ctx.destination); s.start(0);
        } catch (e) {}
        preloadSelected();
      }
    } else if (ctx.state !== "running") {
      try { var p = ctx.resume(); if (p && p.catch) p.catch(noop); } catch (e) {}
    }
    updateBell();
  }
  ["pointerdown", "pointerup", "touchend", "click", "keydown"].forEach(function (ev) {
    document.addEventListener(ev, onGesture, { passive: true, capture: true });
  });

  /* ---------- bell button ---------- */
  var bell = null, ringTimer = 0;
  function updateBell() {
    if (!bell) return;
    var locked = !(ctx && ctx.state === "running");
    bell.classList.toggle("off", !settings.on);
    bell.classList.toggle("locked", locked);
    var label = settings.on && locked ? tr("title") + " - " + tr("locked") : tr("title");
    bell.setAttribute("aria-label", label);
    bell.title = label;
  }
  function ringBell() {
    if (!bell) return;
    bell.classList.remove("ringing");
    void bell.offsetWidth; // restart the animation
    bell.classList.add("ringing");
    clearTimeout(ringTimer);
    ringTimer = setTimeout(function () { bell.classList.remove("ringing"); }, 1000);
  }

  /* ---------- settings panel ---------- */
  var overlay = null, ui = {};
  var ICON_PLAY = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M11 5 6 9H2v6h4l5 4V5z"/><path d="M15.5 8.5a5 5 0 0 1 0 7"/><path d="M18.5 5.5a9 9 0 0 1 0 13"/></svg>';

  function buildPanel() {
    overlay = document.createElement("div");
    overlay.className = "sp-overlay";
    overlay.hidden = true;
    overlay.innerHTML =
      '<div class="sp-sheet" role="dialog" aria-modal="true" aria-labelledby="spTitle">' +
        '<div class="sp-grab"></div>' +
        '<div class="sp-head"><h3 id="spTitle"></h3>' +
          '<button type="button" class="sp-close"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" aria-hidden="true"><path d="M6 6l12 12M18 6 6 18"/></svg></button></div>' +
        '<label class="sp-row sp-main">' +
          '<span class="sp-txt"><b class="sp-enable"></b><small class="sp-hint"></small></span>' +
          '<span class="sp-switch"><input type="checkbox" class="sp-on"><span class="sp-knob"></span></span>' +
        '</label>' +
        '<div class="sp-dim">' +
          '<div class="sp-row sp-volhead"><b class="sp-volabel"></b><span class="sp-volval"></span></div>' +
          '<input type="range" class="sp-vol" min="0" max="100" step="1">' +
          '<p class="sp-tip"></p>' +
          '<h4 class="sp-h sp-hstart"></h4><div class="sp-chips sp-lstart"></div>' +
          '<h4 class="sp-h sp-hend"></h4><div class="sp-chips sp-lend"></div>' +
        '</div>' +
        '<p class="sp-foot"></p>' +
      '</div>';
    document.body.appendChild(overlay);

    var q = function (s) { return overlay.querySelector(s); };
    ui = {
      sheet: q(".sp-sheet"), title: q("#spTitle"), close: q(".sp-close"),
      enable: q(".sp-enable"), hint: q(".sp-hint"), on: q(".sp-on"),
      dim: q(".sp-dim"), volLabel: q(".sp-volabel"), volVal: q(".sp-volval"), vol: q(".sp-vol"),
      tip: q(".sp-tip"), hStart: q(".sp-hstart"), hEnd: q(".sp-hend"),
      lStart: q(".sp-lstart"), lEnd: q(".sp-lend"), foot: q(".sp-foot"),
    };

    ui.close.addEventListener("click", close);
    overlay.addEventListener("click", function (e) { if (e.target === overlay) close(); });
    document.addEventListener("keydown", function (e) { if (e.key === "Escape" && isOpen()) close(); });

    ui.on.addEventListener("change", function () {
      settings.on = ui.on.checked;
      saveSettings(); renderPanel(); updateBell();
    });
    ui.vol.addEventListener("input", function () {
      settings.vol = Number(ui.vol.value);
      applyVolume(); saveSettings(); renderVolume();
    });
    ui.vol.addEventListener("change", function () { play(settings.start, true); }); // hear the new level
  }

  function renderVolume() {
    ui.vol.value = settings.vol;
    ui.volVal.textContent = settings.vol + "%";
    ui.vol.style.setProperty("--fill", settings.vol + "%");
  }

  function renderChips(box, key) {
    box.replaceChildren();
    box.setAttribute("role", "radiogroup");
    SOUNDS.forEach(function (s) {
      var b = document.createElement("button");
      b.type = "button";
      b.className = "sp-chip" + (settings[key] === s.id ? " sel" : "");
      b.setAttribute("role", "radio");
      b.setAttribute("aria-checked", settings[key] === s.id ? "true" : "false");
      var n = document.createElement("span");
      n.className = "sp-name";
      n.textContent = soundName(s.id);
      var ic = document.createElement("span");
      ic.className = "sp-ico";
      ic.innerHTML = ICON_PLAY;
      b.append(n, ic);
      b.addEventListener("click", function () {
        settings[key] = s.id;
        saveSettings(); preloadSelected();
        renderChips(ui.lStart, "start");
        renderChips(ui.lEnd, "end");
        play(s.id, true);
      });
      box.appendChild(b);
    });
  }

  function renderPanel() {
    if (!overlay) return;
    ui.title.textContent = tr("title");
    ui.close.setAttribute("aria-label", tr("close"));
    ui.enable.textContent = tr("enable");
    ui.hint.textContent = tr("enableHint");
    ui.on.checked = settings.on;
    ui.sheet.classList.toggle("sp-off", !settings.on);
    ui.volLabel.textContent = tr("volume");
    ui.tip.textContent = tr("tip");
    ui.hStart.textContent = tr("start");
    ui.hEnd.textContent = tr("end");
    ui.foot.textContent = tr("saved");
    renderVolume();
    renderChips(ui.lStart, "start");
    renderChips(ui.lEnd, "end");
  }

  function isOpen() { return overlay && !overlay.hidden; }
  function open() {
    if (!overlay) return;
    renderPanel();
    overlay.hidden = false;
    document.documentElement.style.overflow = "hidden";
    requestAnimationFrame(function () { overlay.classList.add("show"); });
    setTimeout(function () { try { ui.close.focus({ preventScroll: true }); } catch (e) {} }, 60);
  }
  function close() {
    if (!overlay || overlay.hidden) return;
    overlay.classList.remove("show");
    document.documentElement.style.overflow = "";
    setTimeout(function () { overlay.hidden = true; }, 260);
    if (bell) try { bell.focus({ preventScroll: true }); } catch (e) {}
  }

  function refreshLang() { renderPanel(); updateBell(); }

  function mount() {
    bell = document.getElementById("soundBell");
    buildPanel();
    if (bell) bell.addEventListener("click", function () { isOpen() ? close() : open(); });
    renderPanel();
    updateBell();
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", mount);
  else mount();

  window.SJSound = {
    watch: watch, play: function (id) { return play(id, true); },
    open: open, close: close, refreshLang: refreshLang,
    _test: { SYNTH: SYNTH, SOUNDS: SOUNDS, events: events, settings: function () { return settings; }, buffers: buffers },
  };
})();
